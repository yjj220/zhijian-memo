$map = @{}
foreach ($line in ($translations -split "`r?`n")) {
    $parts = $line -split '=', 2
    if ($parts.Count -eq 2) { $map[$parts[0]] = $parts[1].Replace('\n', "`n") }
}
$source = Join-Path $PSScriptRoot '..\stickypad\Resources\Strings.resx'
$target = Join-Path $PSScriptRoot '..\stickypad\Resources\Strings.zh-CN.resx'
$xml = [xml](Get-Content -LiteralPath $source -Raw -Encoding utf8)
foreach ($entry in $xml.root.data) {
    if (-not $map.ContainsKey($entry.name)) { throw "Missing translation: $($entry.name)" }
    $entry.value = $map[$entry.name]
}
$xml.Save($target)
Write-Output "Translated $($xml.root.data.Count) resource strings."
